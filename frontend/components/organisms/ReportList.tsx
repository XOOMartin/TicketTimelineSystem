import { formatDateTime, formatShortDay } from 'lib/dates'
import { plural } from 'lib/text'
import { ReportSummary } from 'types/worklog'

import styles from 'styles/ReportList.module.css'

type Props = {
  reports: ReportSummary[]
  selectedId: string | null
  onSelect: (id: string) => void
}

// The saved reports as a row of chips: the period, then its kind and size.
// Who generated it and when is on hover.
export default function ReportList(props: Props) {
  const { reports, selectedId, onSelect } = props

  if (reports.length === 0) {
    return <p className={styles.empty}>No reports yet.</p>
  }

  return (
    <ul className={styles.list}>
      {reports.map((r) => (
        <li key={r.id}>
          <button
            type="button"
            className={r.id === selectedId ? `${styles.item} ${styles.selected}` : styles.item}
            aria-current={r.id === selectedId ? 'true' : undefined}
            onClick={() => onSelect(r.id)}
            title={`Generated by ${r.generatedBy} · ${formatDateTime(r.generatedAt)}`}
          >
            <span className={styles.title}>
              {r.kind === 'weekly'
                ? `${formatShortDay(r.period.first)} – ${formatShortDay(r.period.last)}`
                : formatShortDay(r.period.first)}
            </span>
            <span className={styles.meta}>
              <span className={r.kind === 'weekly' ? `${styles.kind} ${styles.weekly}` : styles.kind}>
                {r.kind === 'weekly' ? 'Weekly' : 'Daily'}
              </span>
              {plural(r.ticketCount, 'ticket')}
            </span>
          </button>
        </li>
      ))}
    </ul>
  )
}
