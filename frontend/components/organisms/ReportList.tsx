import Icon from 'components/atoms/Icon'
import { formatDateTime } from 'lib/dates'
import { REPORT_KIND_LABELS, reportDays } from 'lib/reports'
import { plural } from 'lib/text'
import { ReportSummary } from 'types/worklog'

import styles from 'styles/ReportList.module.css'

type Props = {
  reports: ReportSummary[]
  selectedId: string | null
  onSelect: (id: string) => void
  // The × in a chip's corner: asks first, then deletes the report
  onDelete: (report: ReportSummary) => void
}

// The saved reports as a row of chips: the period, then its kind and size,
// with an × in the corner to delete it. Who generated it and when is on hover.
export default function ReportList(props: Props) {
  const { reports, selectedId, onSelect, onDelete } = props

  if (reports.length === 0) {
    return <p className={styles.empty}>No reports yet.</p>
  }

  return (
    <ul className={styles.list}>
      {reports.map((r) => (
        <li key={r.id}>
          <button
            type="button"
            className={r.id === selectedId ? `${styles.item} ${styles.selected}` : styles.item}
            aria-current={r.id === selectedId ? 'true' : undefined}
            onClick={() => onSelect(r.id)}
            title={`Generated by ${r.generatedBy} · ${formatDateTime(r.generatedAt)}`}
          >
            <span className={styles.title}>{reportDays(r)}</span>
            <span className={styles.meta}>
              <span className={r.kind === 'weekly' ? `${styles.kind} ${styles.weekly}` : styles.kind}>
                {REPORT_KIND_LABELS[r.kind]}
              </span>
              {plural(r.ticketCount, 'ticket')}
            </span>
          </button>
          {/* Beside the chip's button, not in it: a button can't hold another */}
          <button
            type="button"
            className={styles.remove}
            onClick={() => onDelete(r)}
            aria-label={`Delete the ${REPORT_KIND_LABELS[r.kind].toLowerCase()} report for ${reportDays(r)}`}
            title="Delete this report"
          >
            <Icon name="close" size={12} />
          </button>
        </li>
      ))}
    </ul>
  )
}
