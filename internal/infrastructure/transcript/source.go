package transcript

import (
	"bufio"
	"bytes"
	"context"
	"encoding/json"
	"errors"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"time"

	"crud_app/internal/domain/activity"
)

// Source reads the prompts the user typed into Claude Code from the session
// transcripts it keeps at <dir>/<project>/<session>.jsonl (one JSON record per line).
type Source struct {
	dir string
}

func NewSource(dir string) *Source {
	return &Source{dir: dir}
}

func (s *Source) Prompts(ctx context.Context) ([]*activity.Prompt, error) {
	paths, err := filepath.Glob(filepath.Join(s.dir, "*", "*.jsonl"))
	if err != nil {
		return nil, err
	}
	var prompts []*activity.Prompt
	for _, path := range paths {
		if err := ctx.Err(); err != nil {
			return nil, err
		}
		found, err := readFile(path)
		if err != nil {
			return nil, err
		}
		prompts = append(prompts, found...)
	}
	return prompts, nil
}

// record holds the fields we need from one transcript line.
type record struct {
	Type        string    `json:"type"`
	UUID        string    `json:"uuid"`
	SessionID   string    `json:"sessionId"`
	Cwd         string    `json:"cwd"`
	GitBranch   string    `json:"gitBranch"`
	Timestamp   time.Time `json:"timestamp"`
	IsMeta      bool      `json:"isMeta"`
	IsSidechain bool      `json:"isSidechain"`
	Origin      *struct {
		Kind string `json:"kind"`
	} `json:"origin"`
	Message struct {
		Content json.RawMessage `json:"content"`
	} `json:"message"`
}

// Transcripts are hundreds of MB; most lines are tool output. Checking for this
// marker first lets us skip them without decoding the JSON.
var userMarker = []byte(`"type":"user"`)

func readFile(path string) ([]*activity.Prompt, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()

	var prompts []*activity.Prompt
	reader := bufio.NewReaderSize(f, 1<<20)
	for {
		line, readErr := reader.ReadBytes('\n')
		if bytes.Contains(line, userMarker) {
			if p := parseLine(line); p != nil {
				prompts = append(prompts, p)
			}
		}
		if errors.Is(readErr, io.EOF) {
			return prompts, nil
		}
		if readErr != nil {
			return nil, readErr
		}
	}
}

// parseLine returns nil for anything that isn't a prompt the user typed.
func parseLine(line []byte) *activity.Prompt {
	var r record
	if err := json.Unmarshal(line, &r); err != nil {
		return nil
	}
	if r.Type != "user" || r.IsMeta || r.IsSidechain {
		return nil
	}
	// Newer transcripts mark typed prompts with origin.kind "human"; others
	// (task notifications etc.) are generated by Claude Code itself.
	if r.Origin != nil && r.Origin.Kind != "human" {
		return nil
	}

	text := clean(contentText(r.Message.Content))
	if text == "" {
		return nil
	}
	p, err := activity.NewPrompt(activity.ID(r.UUID), r.SessionID, r.Cwd, r.GitBranch, text, r.Timestamp)
	if err != nil {
		return nil
	}
	return p
}

// contentText returns the text of a message whose content is either a plain
// string or a list of blocks. Tool results have no text blocks, so they give "".
func contentText(raw json.RawMessage) string {
	var s string
	if json.Unmarshal(raw, &s) == nil {
		return s
	}
	var blocks []struct {
		Type string `json:"type"`
		Text string `json:"text"`
	}
	if json.Unmarshal(raw, &blocks) != nil {
		return ""
	}
	var parts []string
	for _, b := range blocks {
		if b.Type == "text" {
			parts = append(parts, b.Text)
		}
	}
	return strings.Join(parts, "\n")
}

var (
	// Context the editor adds to a prompt; the user didn't type it.
	injectedRE   = regexp.MustCompile(`(?s)<(?:system-reminder|ide_opened_file|ide_selection)>.*?</(?:system-reminder|ide_opened_file|ide_selection)>`)
	pasteOpenRE  = regexp.MustCompile(`<pasted_content[^>]*>`)
	pasteCloseRE = regexp.MustCompile(`</pasted_content[^>]*>`)
	commandRE    = regexp.MustCompile(`<command-name>/?([^<]+)</command-name>`)
	commandArgRE = regexp.MustCompile(`(?s)<command-args>(.*?)</command-args>`)
)

// Slash commands that only manage the session, not real requests.
var housekeepingCommands = map[string]bool{
	"clear": true, "compact": true, "model": true, "config": true, "cost": true, "exit": true,
	"resume": true, "status": true, "login": true, "logout": true, "context": true, "fast": true,
}

func clean(text string) string {
	if m := commandRE.FindStringSubmatch(text); m != nil {
		name := strings.TrimSpace(m[1])
		if housekeepingCommands[name] {
			return ""
		}
		cmd := "/" + name
		if a := commandArgRE.FindStringSubmatch(text); a != nil && strings.TrimSpace(a[1]) != "" {
			cmd += " " + strings.TrimSpace(a[1])
		}
		return cmd
	}
	if strings.HasPrefix(strings.TrimSpace(text), "<") &&
		(strings.Contains(text, "<task-notification>") || strings.Contains(text, "<local-command-")) {
		return ""
	}

	text = injectedRE.ReplaceAllString(text, "")
	text = strings.ReplaceAll(text, "[Request interrupted by user]", "")
	text = pasteOpenRE.ReplaceAllString(text, "[pasted]\n")
	text = pasteCloseRE.ReplaceAllString(text, "\n[/pasted]")
	return strings.TrimSpace(text)
}
